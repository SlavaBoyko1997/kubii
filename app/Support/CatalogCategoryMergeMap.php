    /**
     * Pick the merge target that actually exists in the database.
     * Prefers the canonical target id; falls back to the first existing source.
     *
     * @param  list<int>  $sourceIds
     */
    public static function resolveTargetId(int $preferredTarget, array $sourceIds, callable $exists): ?int
    {
        if ($exists($preferredTarget)) {
            return $preferredTarget;
        }

        foreach ($sourceIds as $sourceId) {
            $sourceId = (int) $sourceId;

            if ($sourceId === $preferredTarget) {
                continue;
            }

            if ($exists($sourceId)) {
                return $sourceId;
            }
        }

        return null;
    }

    /**
     * @param  callable(int): bool  $exists
     * @return array<int, int>
     */
    public static function buildSourceTargetPairs(callable $exists): array
    {
        $pairs = [];

        foreach (self::merges() as $merge) {
            $target = self::resolveTargetId((int) $merge['target'], $merge['sources'], $exists);

            if ($target === null) {
                continue;
            }

            foreach ($merge['sources'] as $source) {
                $source = (int) $source;

                if ($source === $target) {
                    continue;
                }

                $pairs[$source] = $target;
            }
        }

        return $pairs;
    }

