    public function show(string $page, CatalogCache $cache, SeoSchema $seoSchema, SeoMeta $seoMeta): View
    {
        abort_unless(isset(self::PAGES[$page]), 404);

        $data = $cache->remember('page:v13:'.$page, fn (): array => $this->pageData($page));
        $url = localized_route('pages.show', $page);
        $type = match ($page) {
            'about' => 'AboutPage',
            'contacts' => 'ContactPage',
            default => 'WebPage',
        };

        return view('pages.show', [
            ...$data,
            'page' => $page,
            'canonicalUrl' => $url,
            'seoSchema' => $seoSchema->page($data['title'], $data['description'], $url, $type),
            'seoMeta' => $seoMeta->page($data['title'], $data['description'], $url),
        ]);
    }

    /**
     * @return array{title: string, description: string, sections: array<int, array{heading?: string, paragraphs?: array<int, string>, items?: array<int, string>}>}
     */
    private function pageData(string $page): array
    {
        $locale = Locale::current();
        $content = self::PAGES[$page][$locale];

        if (isset($content['title'])) {
            if ($page === 'delivery' && FreeDelivery::threshold() > 0) {
                $amount = FreeDelivery::formattedThreshold();
                $content['sections'][0]['paragraphs'][] = $locale === 'ru'
                    ? "Для заказов от {$amount} ₴ доставка «Новой Почтой» — бесплатная."
                    : "Для замовлень від {$amount} ₴ доставка «Новою Поштою» — безкоштовна.";
            }

            $content['sections'] = $this->resolveDynamicSections($content['sections'], $locale);

            return $content;
        }

        return [
            'title' => $content[0],
            'description' => $content[1],
            'sections' => [
                ['paragraphs' => [$content[1]]],
            ],
        ];
    }

    /**
     * Fills in the "__STORE_*__" markers used above with the real seller
     * identity, so it only ever needs to be maintained in one place
     * (config/store.php) instead of being duplicated per page/locale.
     *
     * @param  array<int, array<string, mixed>>  $sections
     * @return array<int, array<string, mixed>>
     */
    private function resolveDynamicSections(array $sections, string $locale): array
    {
        $phone = (string) (StoreInfo::phone() ?? '+38 (099) 148-73-48');

        return array_map(function (array $section) use ($locale, $phone): array {
            if (($section['details'] ?? null) === '__STORE_SELLER__') {
                $section['details'] = $this->sellerDetails($locale);
            }

            if (($section['details'] ?? null) === '__STORE_CONTACTS__') {
                $section['details'] = $this->publicContactDetails($locale);
            }

            if (($section['details'] ?? null) === '__STORE_PRIVACY_CONTACT__') {
                $section['details'] = $this->privacyContactDetails();
            }

            $replacePhone = static fn (string $text): string => str_replace(
                ['__SELLER__', '__PHONE__'],
                [StoreInfo::legalName($locale), $phone],
                $text,
            );

            if (! empty($section['paragraphs'])) {
                $section['paragraphs'] = array_map($replacePhone, $section['paragraphs']);
            }

            if (! empty($section['paragraphs_after'])) {
                $section['paragraphs_after'] = array_map($replacePhone, $section['paragraphs_after']);
            }

            if (! empty($section['items'])) {
                $section['items'] = array_map($replacePhone, $section['items']);
            }

            return $section;
        }, $sections);
    }

    /**
     * @return array<string, array{text: string, href?: string}>
     */
    private function publicContactDetails(string $locale): array
    {
        $details = [];
        $phone = StoreInfo::phone() ?? '+38 (099) 148-73-48';
        $phoneLabel = $locale === 'ru' ? 'Телефон / Telegram' : 'Телефон / Telegram';

        $details[$phoneLabel] = [
            'href' => 'tel:'.$this->telHref($phone),
            'text' => $phone,
        ];

        if ($telegram = StoreInfo::telegramUrl()) {
            $details['Telegram'] = [
                'href' => $telegram,
                'text' => $phone,
            ];
        }

        if ($instagram = StoreInfo::instagramUrl()) {
            $details['Instagram'] = [
                'href' => $instagram,
                'text' => 'bash.camp',
            ];
        }

        if (StoreInfo::email()) {
            $details['Email'] = [
                'href' => 'mailto:'.StoreInfo::email(),
                'text' => (string) StoreInfo::email(),
            ];
        }

        return $details;
    }

    /**
     * @return array<string, array{text: string, href?: string}>
     */
    private function sellerDetails(string $locale): array
    {
        $labels = $locale === 'ru'
            ? [
                'seller' => 'Продавец',
                'director' => 'Директор',
                'address' => 'Адрес для корреспонденции',
                'schedule' => 'График работы',
                'tax' => 'ЕГРПОУ',
            ]
            : [
                'seller' => 'Продавець',
                'director' => 'Директор',
                'address' => 'Адреса для листування',
                'schedule' => 'Графік роботи',
                'tax' => 'ЄДРПОУ',
            ];

        $details = [
            $labels['seller'] => ['text' => StoreInfo::legalName($locale)],
        ];

        if (StoreInfo::director($locale) !== '') {
            $details[$labels['director']] = ['text' => StoreInfo::director($locale)];
        }

        $details[$labels['address']] = ['text' => StoreInfo::address($locale)];

        if (StoreInfo::hasPhone()) {
            $details['Телефон'] = ['href' => 'tel:'.$this->telHref((string) StoreInfo::phone()), 'text' => (string) StoreInfo::phone()];
        }

        if (StoreInfo::email()) {
            $details['Email'] = ['href' => 'mailto:'.StoreInfo::email(), 'text' => (string) StoreInfo::email()];
        }

        $details[$labels['schedule']] = ['text' => StoreInfo::schedule($locale)];
        $details[$labels['tax']] = ['text' => StoreInfo::taxId()];

        return $details;
    }

